#!/usr/bin/env python3
"""Build Design Tokens into CSS variables, TypeScript exports and Kotlin Compose theme (Task T1.073 / TC1.163)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS_DIR = ROOT / "tokens"
DIST_DIR = ROOT / "dist"
SRC_DIR = ROOT / "src"
COMPOSE_DIR = ROOT / "build" / "compose"

DIST_DIR.mkdir(parents=True, exist_ok=True)
SRC_DIR.mkdir(parents=True, exist_ok=True)
COMPOSE_DIR.mkdir(parents=True, exist_ok=True)


def load_all_tokens() -> dict:
    tokens = {}
    for p in TOKENS_DIR.glob("*.json"):
        tokens.update(json.loads(p.read_text(encoding="utf-8")))
    return tokens


def build_css(tokens: dict) -> str:
    lines = [
        "/* Generated by SCMTIPS Field Token Builder - DO NOT EDIT MANUALLY */",
        ":root {",
    ]

    # Spacing
    for k, v in tokens.get("spacing", {}).items():
        lines.append(f"  --field-space-{k}: {v['value']};")

    # Typography
    for k, v in tokens.get("typography", {}).get("fontSize", {}).items():
        lines.append(f"  --field-font-size-{k}: {v['value']};")
    for k, v in tokens.get("typography", {}).get("fontFamily", {}).items():
        lines.append(f"  --field-font-{k}: {v['value']};")

    # Light colors
    for k, v in tokens.get("color", {}).get("light", {}).items():
        lines.append(f"  --field-color-{k}: {v['value']};")

    lines.append("}\n")

    # Dark colors
    lines.append("[data-theme='dark'] {")
    for k, v in tokens.get("color", {}).get("dark", {}).items():
        lines.append(f"  --field-color-{k}: {v['value']};")
    lines.append("}\n")

    # Lens HUD
    lines.append(".lens-hud {")
    for k, v in tokens.get("color", {}).get("lens", {}).items():
        lines.append(f"  --field-lens-{k}: {v['value']};")
    lines.append("}\n")

    return "\n".join(lines)


def build_ts(tokens: dict) -> str:
    return f"""// Generated by SCMTIPS Field Token Builder - DO NOT EDIT MANUALLY
export const tokens = {json.dumps(tokens, indent=2)} as const;

export type DesignTokens = typeof tokens;
export default tokens;
"""


def build_kotlin(tokens: dict) -> str:
    light = tokens.get("color", {}).get("light", {})
    lens = tokens.get("color", {}).get("lens", {})
    return f"""package com.scmtips.field.ui.theme

// Generated by SCMTIPS Field Token Builder - DO NOT EDIT MANUALLY

object FieldColors {{
    val Primary = "{light.get("primary", {}).get("value", "#0284C7")}"
    val Background = "{light.get("bg", {}).get("value", "#FFFFFF")}"
    val Surface = "{light.get("surface", {}).get("value", "#F8FAFC")}"
    val Text = "{light.get("text", {}).get("value", "#0F172A")}"
    val TextMuted = "{light.get("textMuted", {}).get("value", "#475569")}"
    val Success = "{light.get("success", {}).get("value", "#15803D")}"
    val Warning = "{light.get("warning", {}).get("value", "#B45309")}"
    val Danger = "{light.get("danger", {}).get("value", "#B91C1C")}"

    // Lens HUD Monochrome Palette
    val LensBackground = "{lens.get("bg", {}).get("value", "#000000")}"
    val LensText = "{lens.get("text", {}).get("value", "#00FF66")}"
    val LensTextDim = "{lens.get("textDim", {}).get("value", "#009933")}"
}}
"""


def main():
    tokens = load_all_tokens()
    (DIST_DIR / "tokens.css").write_text(build_css(tokens), encoding="utf-8")
    (SRC_DIR / "index.ts").write_text(build_ts(tokens), encoding="utf-8")
    (COMPOSE_DIR / "FieldTheme.kt").write_text(build_kotlin(tokens), encoding="utf-8")
    print(f"Generated tokens.css, index.ts and FieldTheme.kt from {len(tokens)} token groups.")


if __name__ == "__main__":
    main()
