-- SCMTIPS Field - Local Development Database Initialization
CREATE DATABASE field;
CREATE DATABASE erpsim;

-- Roles for field database
\c field

CREATE ROLE field_migrator WITH LOGIN PASSWORD 'devpassword' CREATEDB;
CREATE ROLE field_app WITH LOGIN PASSWORD 'devpassword' NOSUPERUSER NOCREATEDB NOBYPASSRLS;
CREATE ROLE field_worker WITH LOGIN PASSWORD 'devpassword' NOSUPERUSER NOCREATEDB NOBYPASSRLS;

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE SCHEMA IF NOT EXISTS field;
GRANT ALL ON SCHEMA field TO field_migrator;
GRANT USAGE ON SCHEMA field TO field_app, field_worker;
ALTER DEFAULT PRIVILEGES IN SCHEMA field GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO field_app, field_worker;
ALTER DEFAULT PRIVILEGES IN SCHEMA field GRANT USAGE, SELECT ON SEQUENCES TO field_app, field_worker;

-- Roles for erpsim database
\c erpsim

CREATE ROLE erpsim_app WITH LOGIN PASSWORD 'devpassword' NOSUPERUSER NOCREATEDB;

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE SCHEMA IF NOT EXISTS erpsim;
GRANT ALL ON SCHEMA erpsim TO erpsim_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA erpsim GRANT ALL ON TABLES TO erpsim_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA erpsim GRANT ALL ON SEQUENCES TO erpsim_app;
